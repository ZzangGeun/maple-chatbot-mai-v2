"""
Gemini LLM 전용 프롬프트 상수

Gemini는 ChatML 특수 태그(<|im_start|> 등)가 필요 없으므로
일반 텍스트 형식으로 작성합니다.
"""

# (1) 질문 분류 프롬프트
